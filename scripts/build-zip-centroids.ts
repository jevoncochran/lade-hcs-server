import { readFileSync, writeFileSync } from 'node:fs';

// Builds src/mileage/data/fl-zip-centroids.ts from the US Census Bureau's
// ZCTA Gazetteer (public domain), for the estimated-distance stand-in.
//
//   1. Download https://www2.census.gov/geo/docs/maps-data/data/gazetteer/
//      2025_Gazetteer/2025_Gaz_zcta_national.zip and unzip it.
//   2. npx tsx scripts/build-zip-centroids.ts path/to/2025_Gaz_zcta_national.txt
//
// Keeps Florida ZIPs only (320xx–349xx): Lade only operates in Florida.
const [, , inputPath] = process.argv;
if (!inputPath) {
  console.error('Usage: tsx scripts/build-zip-centroids.ts <gazetteer .txt>');
  process.exit(1);
}

const [header, ...rows] = readFileSync(inputPath, 'utf8').trim().split('\n');
const columns = header.trim().split('|');
const zipCol = columns.indexOf('GEOID');
const latCol = columns.indexOf('INTPTLAT');
const lonCol = columns.indexOf('INTPTLONG');
if ([zipCol, latCol, lonCol].includes(-1)) {
  throw new Error(`Unexpected columns: ${columns.join(', ')}`);
}

const entries = rows
  .map((row) => row.trim().split('|'))
  .filter((cells) => /^3[2-4]\d{3}$/.test(cells[zipCol]))
  .map((cells) => {
    const lat = Number(cells[latCol]);
    const lon = Number(cells[lonCol]);
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) {
      throw new Error(`Bad coordinates for ${cells[zipCol]}`);
    }
    // 4 decimals ≈ 11 meters: plenty for a ZIP-level estimate.
    return `  '${cells[zipCol]}': [${lat.toFixed(4)}, ${lon.toFixed(4)}],`;
  });

writeFileSync(
  'src/mileage/data/fl-zip-centroids.ts',
  `// GENERATED by scripts/build-zip-centroids.ts — do not edit by hand.
// Source: US Census Bureau, 2025 ZCTA Gazetteer (public domain). Each Florida
// ZIP code's internal point as [latitude, longitude]. Used only by the
// estimated-distance stand-in, never for real billing.
export const FL_ZIP_CENTROIDS: Readonly<Record<string, readonly [number, number]>> = {
${entries.join('\n')}
};
`,
);
console.log(`Wrote ${entries.length} Florida ZIP codes.`);
